#!/usr/bin/env python3
"""Embed a maintainer-owned, public Google iOS client configuration."""
import argparse
import os
from pathlib import Path
import plistlib
import re

DEFAULT_BUNDLE_ID = "org.folia.community.ios"
GOOGLE_URL_NAME = "Syllume Google Login"
LEGACY_GOOGLE_URL_NAME = "Folia Google Login"


def configure(plist_path, xcconfig_path, client_id, bundle_id, require=False, build_bundle_id=""):
    client_id, bundle_id = client_id.strip(), bundle_id.strip()
    build_bundle_id = build_bundle_id.strip() or DEFAULT_BUNDLE_ID
    if bool(client_id) != bool(bundle_id):
        raise ValueError("Set both GOOGLE_IOS_CLIENT_ID and GOOGLE_IOS_BUNDLE_ID.")
    if require and not client_id:
        raise ValueError("Google login is required for this build; configure the two repository variables first.")
    if client_id and not re.fullmatch(r"[A-Za-z0-9_-]+\.apps\.googleusercontent\.com", client_id):
        raise ValueError("GOOGLE_IOS_CLIENT_ID must be an iOS OAuth client ID ending in .apps.googleusercontent.com.")
    if bundle_id and not re.fullmatch(r"[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+", bundle_id):
        raise ValueError("GOOGLE_IOS_BUNDLE_ID must be a bundle identifier without spaces or wildcards.")
    if not re.fullmatch(r"[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+", build_bundle_id):
        raise ValueError("FOLIA_BUILD_BUNDLE_ID must be a bundle identifier without spaces or wildcards.")
    info = plistlib.loads(Path(plist_path).read_bytes())
    url_types = [entry for entry in info.get("CFBundleURLTypes", [])
                 if entry.get("CFBundleURLName") not in {GOOGLE_URL_NAME, LEGACY_GOOGLE_URL_NAME}]
    if client_id:
        scheme = ".".join(reversed(client_id.split(".")))
        url_types.append({"CFBundleURLName": GOOGLE_URL_NAME, "CFBundleURLSchemes": [scheme]})
    info["CFBundleURLTypes"] = url_types
    info["FoliaGoogleClientID"] = client_id
    info["FoliaGoogleBundleID"] = bundle_id
    # Validate every input before touching either output file.
    plist_data = plistlib.dumps(info, sort_keys=False)
    config = "// Generated by Tools/configure_google_oauth.py; public app identifier only.\n"
    config += "FOLIA_APP_BUNDLE_ID = " + build_bundle_id + "\n"
    Path(plist_path).write_bytes(plist_data)
    Path(xcconfig_path).write_text(config, encoding="utf-8")
    return {"bundle_id": build_bundle_id, "google_bundle_id": bundle_id, "google_configured": bool(client_id)}


def main():
    ios_dir = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--require-configured", action="store_true")
    args = parser.parse_args()
    try:
        result = configure(ios_dir / "Syllume/Resources/Info.plist", ios_dir / "GoogleOAuth.xcconfig",
                           os.environ.get("GOOGLE_IOS_CLIENT_ID", ""),
                           os.environ.get("GOOGLE_IOS_BUNDLE_ID", ""), args.require_configured,
                           os.environ.get("FOLIA_BUILD_BUNDLE_ID", ""))
    except ValueError as error:
        parser.error(str(error))
    enabled = "true" if result["google_configured"] else "false"
    if path := os.environ.get("GITHUB_ENV"):
        with open(path, "a", encoding="utf-8") as output:
            output.write("FOLIA_GOOGLE_READY=" + enabled + "\n")
    if path := os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(path, "a", encoding="utf-8") as output:
            output.write("Google login configured: **" + enabled + "**\n\n")
            output.write("Build Bundle ID (before signing): `" + result["bundle_id"] + "`\n\n")
            output.write("Google registered Bundle ID (after signing): `" + result["google_bundle_id"] + "`\n")
    print("Google login configured: " + enabled + "; build Bundle ID: " + result["bundle_id"]
          + "; Google registered Bundle ID: " + result["google_bundle_id"])


if __name__ == "__main__":
    main()
